export function confirmLabel(values = []) {
  if (!values.length) return 'Confirm';
  const shown = values.slice(0, 2).map((v) => v.value).join(', ');
  const rest = values.length - 2;
  return `Confirm · including ${shown}${rest > 0 ? ` and ${rest} more` : ''}`;
}

